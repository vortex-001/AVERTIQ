def seed_demo_dataset(db: Session) -> dict:
    """
    Seeds exactly 50 realistic Punjab emergency incidents & reports.
    Distribution: 5 Critical, 12 High, 18 Medium, 15 Low across 12 Punjab cities.
    Idempotent: removes previous demo records before inserting.
    """
    now = datetime.now(timezone.utc)

    # 1. Seed or ensure admin and coordinator accounts
    users_data = [
        {"email": "admin@avertiq.org", "name": "Deepak Sharma (Admin)", "role": "admin", "pwd": "AdminPassword123!"},
        {"email": "coordinator@avertiq.org", "name": "Harpreet Kaur (Coordinator)", "role": "coordinator", "pwd": "Coordinator123!"},
        {"email": "viewer@avertiq.org", "name": "Ananya Sen (Observer)", "role": "viewer", "pwd": "Viewer123!"},
    ]
    for u in users_data:
        existing = db.query(User).filter(User.email == u["email"]).first()
        if not existing:
            db.add(User(
                email=u["email"],
                full_name=u["name"],
                role=u["role"],
                hashed_password=get_password_hash(u["pwd"]),
                is_active=True
            ))

    # 2. Clear existing demo incidents & demo reports
    old_demo_reports = db.query(Report).filter(Report.is_demo == True).all()
    for r in old_demo_reports:
        db.delete(r)
    old_demo_incidents = db.query(Incident).filter(Incident.is_demo == True).all()
    for inc in old_demo_incidents:
        db.delete(inc)
    db.commit()

    created_incidents = []
    created_reports = []

    # 3. Insert exactly 50 incidents and reports
    for idx, item in enumerate(PUNJAB_50_REPORTS, start=1):
        minutes_ago = (51 - idx) * 3
        created_time = now - timedelta(minutes=minutes_ago)
        eta_minutes = item.get("eta")
        arrival_time = (created_time + timedelta(minutes=eta_minutes)) if eta_minutes else None

        inc = Incident(
            canonical_title=item["title"],
            incident_type=item["type"],
            description=f"[{item['city']}, Punjab] {item['text']}",
            latitude=item["lat"],
            longitude=item["lon"],
            location_name=item["location"],
            location_accuracy_radius_m=250.0 if item["severity"] in ["critical", "high"] else 500.0,
            is_location_confirmed=True,
            priority_score=item["score"],
            priority_level=item["severity"],
            priority_explanation=f"Demo Scenario {idx}/50 • Threat level: {item['severity'].upper()} in {item['city']} • Estimated Affected: {item.get('affected', 0)}",
            priority_factors={"severity_weight": item["score"], "affected_people": item.get("affected", 0), "district": item["city"]},
            status="under_review" if item["status"] in ["received", "under_review"] else "resolved" if item["status"] == "resolved" else "triaged",
            verification_status="human_verified" if item["severity"] in ["critical", "high"] else "partially_corroborated",
            report_count=1,
            estimated_response_minutes=eta_minutes,
            expected_arrival_at=arrival_time,
            assigned_coordinator_id="admin@avertiq.org",
            response_team_name=item.get("team"),
            response_notes=item.get("notes"),
            response_status=item["status"],
            is_demo=True,
            created_at=created_time,
            updated_at=created_time + timedelta(minutes=5),
        )
        db.add(inc)
        db.flush()

        # Seed Report
        rep = Report(
            incident_id=inc.id,
            original_text=item["text"],
            source_channel=item["channel"],
            language=item["lang"],
            language_mixture=item["lang_name"],
            location_description=item["location"],
            latitude=item["lat"],
            longitude=item["lon"],
            location_source="explicit_reporter",
            location_confidence=0.98 if item["severity"] in ["critical", "high"] else 0.85,
            affected_people_count=item.get("affected"),
            ai_extraction={
                "incident_type": item["type"],
                "urgency": item["severity"],
                "location": item["location"],
                "city": item["city"],
                "is_demo": True,
            },
            raw_metadata={"demo_id": item["id_suffix"], "city": item["city"]},
            is_demo=True,
            created_at=created_time,
        )
        db.add(rep)
        db.flush()

        # Report Embedding
        db.add(ReportEmbedding(
            report_id=rep.id,
            embedding_json=generate_multilingual_embedding(item["text"])
        ))

        # ETA History entry if ETA assigned
        if eta_minutes:
            db.add(IncidentEtaHistory(
                incident_id=inc.id,
                changed_by="Deepak Sharma (Admin)",
                old_eta_minutes=None,
                new_eta_minutes=eta_minutes,
                expected_arrival_at=arrival_time,
                old_status="received",
                new_status=item["status"],
                response_team_name=item.get("team"),
                notes=item.get("notes"),
                created_at=created_time + timedelta(minutes=2)
            ))

        created_incidents.append(inc.id)
        created_reports.append(rep.id)

    # 4. Generate Silent Zone grid cells if none exist
    if db.query(SilentZoneCell).count() == 0:
        cell_dicts = generate_default_grid_cells()
        for c in cell_dicts:
            db.add(SilentZoneCell(
                cell_code=c["cell_code"],
                min_lat=c["min_lat"],
                max_lat=c["max_lat"],
                min_lon=c["min_lon"],
                max_lon=c["max_lon"],
                center_lat=c["center_lat"],
                center_lon=c["center_lon"],
                hazard_score=0.0,
                report_count=0,
                reporting_density=0.0,
                reporting_deficit=0.0,
                vulnerability_score=20.0,
                data_coverage_score=85.0,
                silent_zone_risk=0.0,
                risk_category="low",
                hazard_summary="Baseline sensor coverage normal.",
                explanation="Normal telemetry indicators.",
                recommended_action="Routine monitoring",
                review_status="needs_verification"
            ))

    db.commit()

    return {
        "status": "success",
        "message": f"Successfully seeded exactly {len(created_incidents)} Punjab demo emergency incidents.",
        "breakdown": {
            "total_incidents": len(created_incidents),
            "total_reports": len(created_reports),
            "critical": sum(1 for r in PUNJAB_50_REPORTS if r["severity"] == "critical"),
            "high": sum(1 for r in PUNJAB_50_REPORTS if r["severity"] == "high"),
            "medium": sum(1 for r in PUNJAB_50_REPORTS if r["severity"] == "medium"),
            "low": sum(1 for r in PUNJAB_50_REPORTS if r["severity"] == "low"),
            "cities_represented": len(set(r["city"] for r in PUNJAB_50_REPORTS)),
        }
    }
